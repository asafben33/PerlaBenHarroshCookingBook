ALL_IMAGES = {}
ALL_IMAGES.update(CAT_IMAGES)
ALL_IMAGES.update(RECIPE_IMAGES)

# ─────────────────────────────────────────────────────────────
#  DOWNLOAD FUNCTION
# ─────────────────────────────────────────────────────────────
def download_image(fname: str, url: str, dest: str) -> str:
    """
    Download a single image.
    Returns: 'ok' | 'skip' | 'fail'
    """
    # Skip if file already exists and is large enough
    if os.path.exists(dest) and os.path.getsize(dest) >= MIN_FILE_SIZE_BYTES:
        return "skip"

    if DRY_RUN:
        log.info(f"DRY-RUN  {fname}")
        return "ok"

    try:
        req = urllib.request.Request(url, headers=HEADERS)
        with urllib.request.urlopen(req, timeout=20) as response:
            data = response.read()

        if len(data) < MIN_FILE_SIZE_BYTES:
            raise ValueError(f"Response too small: {len(data)} bytes")

        with open(dest, "wb") as f:
            f.write(data)

        return "ok"

    except Exception as exc:
        log.error(f"FAIL  {fname} — {exc}")
        return "fail"


# ─────────────────────────────────────────────────────────────
#  PROGRESS REPORTER — logs at every 10 % milestone
# ─────────────────────────────────────────────────────────────
def report_progress(current: int, total: int, ok: int, skip: int, fail: int) -> None:
    pct = int(current / total * 100)
    milestone = (pct // 10) * 10
    # Fire once per milestone using a set stored on the function object
    if milestone > 0 and milestone not in report_progress._fired:
        report_progress._fired.add(milestone)
        log.info(
            f"--- PROGRESS {milestone:3d}% ---  "
            f"{current}/{total} images  |  "
            f"OK={ok}  SKIP={skip}  FAIL={fail}"
        )

report_progress._fired: set = set()


# ─────────────────────────────────────────────────────────────
#  MAIN
# ─────────────────────────────────────────────────────────────
def main() -> None:
    total = len(ALL_IMAGES)

    log.info("=" * 60)
    log.info(f"Perla Ben Arosh Cookbook — Image Downloader")
    log.info(f"Mode      : {'DRY-RUN (simulation)' if DRY_RUN else 'LIVE'}")
    log.info(f"Log file  : {_log_path}")
    log.info(f"Target dir: {IMAGES_DIR}")
    log.info(f"Total     : {total} images  "
             f"({len(CAT_IMAGES)} category + {len(RECIPE_IMAGES)} recipe)")
    log.info("=" * 60)

    ok = fail = skip = 0

    for i, (fname, url) in enumerate(ALL_IMAGES.items(), start=1):
        dest   = os.path.join(IMAGES_DIR, fname)
        result = download_image(fname, url, dest)

        if result == "ok":
            ok   += 1
            size  = os.path.getsize(dest) // 1024 if not DRY_RUN else 0
            log.info(f"  [{i:4d}/{total}] OK    {fname} ({size} KB)")
        elif result == "skip":
            skip += 1
            # Log individual skips only for first 5 and every 200th
            if skip <= 5 or skip % 200 == 0:
                log.info(f"  [{i:4d}/{total}] SKIP  {fname}")
        else:
            fail += 1
            # Error already logged inside download_image()

        report_progress(i, total, ok, skip, fail)

        if result != "skip":
            time.sleep(DELAY_BETWEEN_REQUESTS)

    # ── Final summary ──────────────────────────────────────────
    log.info("=" * 60)
    log.info(f"SUMMARY  Downloaded={ok}  Skipped={skip}  Failed={fail}")
    log.info(f"Total in ./images/ folder: {ok + skip}")
    if fail:
        log.warning(f"{fail} file(s) failed — re-run the script to retry them.")
    else:
        log.info("All images downloaded successfully.")
    log.info(f"Log saved to: {_log_path}")
    log.info("=" * 60)


if __name__ == "__main__":
    main()
